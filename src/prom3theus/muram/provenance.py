"""Identify the numerical Stokes generator behind stored synthetic targets."""

from __future__ import annotations

import hashlib
import json
import warnings
from importlib.resources import files

from prom3theus.resources import file_sha256, resource_path

STOKES_FORWARD_CONTRACT_VERSION = 1

# Exclude the inversion network, optimizers, and diagnostics: these change how
# an atmosphere is fitted, not the synthetic spectrum assigned to that atmosphere.
_FORWARD_SOURCES = (
    "rt/_interpolation.py",
    "rt/atomic.py",
    "rt/eos.py",
    "rt/geometry.py",
    "rt/opacity.py",
    "rt/plasma.py",
    "rt/polarization.py",
    "rt/profiles.py",
    "validation/reference_synthesis.py",
    "validation/reference_transfer.py",
    "rt/wavelength.py",
    "rt/zeeman.py",
    "core/constants.py",
    "core/special.py",
    "core/solar_velocity.py",
    "instruments/base.py",
    "muram/atmosphere_builder.py",
    "muram/columns.py",
    "muram/geometry.py",
    "muram/hmi_filter.py",
    "muram/reader.py",
    "muram/synthesize.py",
)
_FORWARD_RESOURCES = (
    "common/abundances.json",
    "common/lines.json",
    "common/stic_continuum_table.json",
    "common/chianti_thermodynamic_table.json",
)


class SyntheticForwardModelWarning(UserWarning):
    """Stored synthetic targets do not establish current forward-model closure."""


def _digest(value):
    return hashlib.sha256(
        json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()


def stokes_forward_provenance(instrument_type):
    """Hash physical resources and source code once when generating a product.

    Source hashes are conservative: even a comment-only edit can make them
    differ. A mismatch signals that closure must be checked, not that spectra
    necessarily changed. No git checkout or network access is required.
    """
    instrument = {
        "hmi_filter_profiles": (
            "instruments/hmi/operator.py",
            "hmi_stokes/instrument_hmi.json",
        ),
        "hinode_sp": (
            "instruments/hinode_sp/operator.py",
            "hinode_sp/instrument_hinode_sp.json",
        ),
    }
    if instrument_type not in instrument:
        raise ValueError(f"Unsupported synthetic Stokes instrument: {instrument_type}")
    source, resource = instrument[instrument_type]
    package = files("prom3theus")
    document = {
        "contract_version": STOKES_FORWARD_CONTRACT_VERSION,
        "instrument_type": instrument_type,
        "implementation_sha256": {
            name: file_sha256(package.joinpath(*name.split("/")))
            for name in (*_FORWARD_SOURCES, source)
        },
        "resource_sha256": {
            name: file_sha256(resource_path(name))
            for name in (*_FORWARD_RESOURCES, resource)
        },
    }
    return {**document, "fingerprint_sha256": _digest(document)}


def check_stokes_forward_provenance(stored, instrument_type):
    """Warn on legacy/mismatched products and retain a machine-readable result.

    Legacy files remain loadable. Matching serialization schemas and passbands
    alone do not establish that they were generated by the current RT solver.
    """
    current = stokes_forward_provenance(instrument_type)
    result = {"current_fingerprint_sha256": current["fingerprint_sha256"]}
    if stored is None or stored == {}:
        warnings.warn(
            "MURaM synthetic Stokes targets lack forward-model provenance. "
            "They may predate optically thick lower-boundary, line-transfer, "
            "axis, or wavelength fixes. "
            "Regenerate the synthetic observations and rebuild preparation caches "
            "before interpreting this as a current-code inversion recovery test.",
            SyntheticForwardModelWarning,
            stacklevel=2,
        )
        return {**result, "status": "legacy_unverified"}
    required = set(current)
    if not isinstance(stored, dict) or set(stored) != required:
        raise ValueError("Invalid MURaM Stokes forward-model provenance")
    claimed = stored["fingerprint_sha256"]
    actual = _digest(
        {key: value for key, value in stored.items() if key != "fingerprint_sha256"}
    )
    if claimed != actual:
        raise ValueError(
            "MURaM Stokes forward-model provenance fingerprint is inconsistent"
        )
    result["stored_fingerprint_sha256"] = claimed
    if stored != current:
        warnings.warn(
            "MURaM synthetic Stokes targets were generated with different "
            "forward-model code or physical resources. A source-only change can "
            "also trigger this warning; verify matched-atmosphere spectral closure "
            "or regenerate the synthetic observations and rebuild preparation caches.",
            SyntheticForwardModelWarning,
            stacklevel=2,
        )
        return {**result, "status": "mismatch"}
    return {**result, "status": "matched"}
